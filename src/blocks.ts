import { subscribe, select, dispatch } from '@wordpress/data';
import { getSetting } from '@woocommerce/settings';

interface PluginSettings {
	no_billing_gateways?: string[];
	store_country?: string;
	store_state?: string;
	store_postcode?: string;
}

interface PaymentStoreSelectors {
	getActivePaymentMethod: () => string | undefined;
}

interface BillingAddress {
	address_1: string;
	address_2: string;
	city: string;
	postcode: string;
	state: string;
	country: string;
	phone: string;
}

interface CartStoreSelectors {
	getCustomerData: () => { billingAddress: BillingAddress };
}

interface CheckoutStoreSelectors {
	isComplete: () => boolean;
}

const PAYMENT_STORE = 'wc/store/payment';
const CART_STORE = 'wc/store/cart';
const CHECKOUT_STORE = 'wc/store/checkout';
const PLUGIN_KEY = 'wc-remove-billing-address-on-free-checkout_data';

// ID of the <style> element injected to hide billing fields.
const STYLE_ID = 'wc-no-billing-address-fields';

const settings = getSetting< PluginSettings >( PLUGIN_KEY, {} );
const noBillingGateways: string[] = settings.no_billing_gateways ?? [];

const DUMMY_ADDRESS: Partial< BillingAddress > = {
	address_1: '__nob__',
	city: '__nob__',
	postcode: settings.store_postcode ?? '00000',
	state: settings.store_state ?? '',
	country: settings.store_country ?? '',
};

// CSS scoped to the checkout billing address block so it cannot bleed onto other pages
// that share the same field IDs (e.g. /my-account/edit-address/billing/).
// Field wrapper class names are generated by form/utils.ts as
// `wc-block-components-address-form__{field_key}`.
const HIDDEN_FIELDS_CSS = `
.wp-block-woocommerce-checkout-billing-address-block .wc-block-components-address-form__address_1,
.wp-block-woocommerce-checkout-billing-address-block .wc-block-components-address-form__address_2,
.wp-block-woocommerce-checkout-billing-address-block .wc-block-components-address-form__city,
.wp-block-woocommerce-checkout-billing-address-block .wc-block-components-address-form__state,
.wp-block-woocommerce-checkout-billing-address-block .wc-block-components-address-form__postcode,
.wp-block-woocommerce-checkout-billing-address-block .wc-block-components-address-form__phone
{ display: none }
`.trim();

function setFieldsVisibility( hidden: boolean ): void {
	if ( hidden ) {
		if ( ! document.getElementById( STYLE_ID ) ) {
			const style = document.createElement( 'style' );
			style.id = STYLE_ID;
			style.textContent = HIDDEN_FIELDS_CSS;
			document.head.appendChild( style );
		}
	} else {
		document.getElementById( STYLE_ID )?.remove();
	}
}

let lastMethod: string | null = null;
let savedBillingAddress: Partial< BillingAddress > | null = null;
let injectedDummyData = false;

	subscribe( () => {

		// Only run on the checkout block page. The billing address block component is reused
// on /my-account/edit-address/billing/ so CSS scoping alone is not sufficient — we
// must not set up any subscriptions outside of a real checkout context.
		if ( !document.querySelector( '.wp-block-woocommerce-checkout' ) ) {
			return;
		}

		const activeMethod = select< PaymentStoreSelectors >(
			PAYMENT_STORE
		).getActivePaymentMethod?.();
		if ( activeMethod === lastMethod ) return;
		const prevMethod = lastMethod;
		lastMethod = activeMethod ?? null;

		const isNoBilling =
			activeMethod !== undefined &&
			noBillingGateways.includes( activeMethod );
		const wasNoBilling =
			prevMethod !== null && noBillingGateways.includes( prevMethod );

		setFieldsVisibility( isNoBilling );

		if ( isNoBilling && ! wasNoBilling ) {
			// Switching TO a no-billing gateway — inject dummy data if fields are empty.
			const billing = select< CartStoreSelectors >(
				CART_STORE
			).getCustomerData?.()?.billingAddress;
			const hasRealData =
				billing?.address_1 || billing?.city || billing?.postcode;
			if ( ! hasRealData ) {
				savedBillingAddress = billing ? { ...billing } : {};
				dispatch( CART_STORE ).setBillingAddress( DUMMY_ADDRESS );
				injectedDummyData = true;
			}
		} else if ( ! isNoBilling && wasNoBilling && injectedDummyData ) {
			// Switching FROM a no-billing gateway — restore original empty address.
			dispatch( CART_STORE ).setBillingAddress(
				savedBillingAddress ?? {
					address_1: '',
					address_2: '',
					city: '',
					postcode: '',
					state: '',
					phone: '',
				}
			);
			savedBillingAddress = null;
			injectedDummyData = false;
		}
	}, PAYMENT_STORE );

	// Remove the hidden-fields stylesheet when the order has been placed, so the
	// style element is gone before any post-order navigation (e.g. to /my-account/).
	subscribe( () => {
		if (
			select< CheckoutStoreSelectors >( CHECKOUT_STORE ).isComplete?.()
		) {
			document.getElementById( STYLE_ID )?.remove();
			savedBillingAddress = null;
			injectedDummyData = false;
		}
	}, CHECKOUT_STORE );

